"""Verification of the phase-3 state estimators (project #102).

The filters are checked where the answer is known: the steady-state inversion reproduces the yaw
rate it was asked for; the per-wheel model collapses to the axle model without load transfer; on a
linear model whose truth is generated by the same equations with the assumed noises, EKF and UKF
agree and are consistent (average NEES inside the χ² band); the augmented UKF recovers a known
friction scale.
"""
import unittest
from dataclasses import replace

import numpy as np

from state_estimation.bicycle import BicycleParams, derivatives, lateral_forces, rk4, steady_state_steer
from state_estimation.filters import EKF, UKF, Model, fy_linear, run
from state_estimation.scenario import consistency, load_calibrated

_, CAR = load_calibrated()
P = BicycleParams.from_car(CAR)
TYRE = CAR.tyre
N, T, DT = 40, 400, 0.02
R = np.diag([0.005 ** 2, 0.5 ** 2, 0.2 ** 2])


def simulate(model, amp, Q, seed):
    """Truth from the model's own equations with process noise Q and measurement noise R."""
    rng = np.random.default_rng(seed)
    t = np.arange(T) * DT
    U = np.zeros((N, T, 2))
    U[..., 0] = amp * np.sin(2 * np.pi * 0.5 * t)[None]
    x = np.tile(np.array([40.0, 0.0, 0.0, 0.005] + ([model.lam_fixed] if model.augmented else [])), (N, 1))
    X, Z = np.empty((N, T, model.n)), np.empty((N, T, 3))
    Lq = np.linalg.cholesky(Q)
    for k in range(T):
        if k:
            x = model.f(x, U[:, k - 1]) + rng.standard_normal((N, model.n)) @ Lq.T
        X[:, k] = x
        Z[:, k] = model.h(x, U[:, k]) + rng.standard_normal((N, 3)) * np.sqrt(np.diag(R))
    return U, X, Z


class SingleTrack(unittest.TestCase):
    def test_steady_state_steer_reproduces_yaw_rate(self):
        vx, r = 50.0, 0.5                                     # 25 m/s², about 2.5 g
        delta, vy = steady_state_steer(P, TYRE, np.array(vx), np.array(r))
        x = np.array([vx, float(vy), r])
        u = np.array([float(delta), 0.0])
        d, ay = derivatives(P, TYRE, x, u)
        self.assertAlmostEqual(float(ay), vx * r, delta=0.02 * vx * r)
        self.assertLess(abs(float(d[2])), 0.05)               # yaw acceleration ≈ 0
        for _ in range(100):                                  # and it stays there for 0.2 s
            x = rk4(P, TYRE, x, u, 0.002)
        self.assertAlmostEqual(float(x[2]), r, delta=0.01)

    def test_per_wheel_equals_axle_without_load_transfer(self):
        p0 = replace(P, h=0.0)
        args = (np.array(45.0), np.array(0.3), np.array(0.4), np.array(0.03), np.array(0.0))
        self.assertTrue(np.allclose(lateral_forces(p0, TYRE, *args), lateral_forces(p0, TYRE, *args, per_wheel=True)))
        f_axle, f_wheel = lateral_forces(P, TYRE, *args), lateral_forces(P, TYRE, *args, per_wheel=True)
        self.assertLess(abs(f_wheel[0]), abs(f_axle[0]))      # load transfer costs grip (concave tyre)


class Filters(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.Q = np.diag([0.05 ** 2, 0.05 ** 2, 0.005 ** 2, 1e-5 ** 2])
        cls.model = Model(P, TYRE, DT, False, 1.0, fy_linear)
        cls.U, cls.X, cls.Z = simulate(cls.model, 0.02, cls.Q, 1)
        rng = np.random.default_rng(2)
        sd0 = np.array([0.2, 0.2, 0.02, 0.005])
        cls.x0 = cls.X[:, 0] + rng.standard_normal((N, 4)) * sd0
        cls.P0 = np.tile(np.diag(sd0 ** 2), (N, 1, 1))
        cls.out = {F.__name__: run(F(cls.model, cls.Q, R), cls.x0, cls.P0, cls.U, cls.Z) for F in (EKF, UKF)}

    def test_ekf_equals_ukf_in_linear_regime(self):
        self.assertLess(np.abs(self.out["EKF"][0] - self.out["UKF"][0]).max(), 1e-4)

    def test_consistent_when_model_matches_truth(self):
        for name, (xs, Ps, nis) in self.out.items():
            avg, (lo, hi) = consistency(xs - self.X, Ps, N)
            inside = np.mean((avg >= lo) & (avg <= hi))
            self.assertGreater(inside, 0.9, name)             # 95 % band: expect ≈ 0.95
            self.assertAlmostEqual(float(np.nanmean(nis)), 3.0, delta=0.15, msg=name)

    def test_augmented_ukf_recovers_friction_scale(self):
        truth = Model(P, TYRE, DT, False, 0.9)
        U, X, Z = simulate(truth, 0.06, np.diag([1e-6] * 4), 3)    # ≈ 2.3 g peaks: tyres near the limit
        ma = Model(P, TYRE, DT, True, 1.0)
        x0 = np.column_stack([X[:, 0], np.full(N, 1.0)])
        P0 = np.tile(np.diag([0.2 ** 2, 0.2 ** 2, 0.02 ** 2, 0.005 ** 2, 0.15 ** 2]), (N, 1, 1))
        Qa = np.diag([0.05 ** 2, 0.05 ** 2, 0.005 ** 2, 1e-5 ** 2, 0.001 ** 2])
        xa, _, _ = run(UKF(ma, Qa, R), x0, P0, U, Z)
        self.assertAlmostEqual(float(xa[:, -1, 4].mean()), 0.9, delta=0.01)


if __name__ == "__main__":
    unittest.main()
