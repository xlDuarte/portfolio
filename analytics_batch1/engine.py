DATA = Path(__file__).resolve().parent / 'data'


def _read(project: int, source: str | Path | None = None) -> pd.DataFrame:
    p = Path(source) if source else DATA / f'{project:03d}.csv'
    d = pd.read_csv(p)
    if d.empty:
        raise ValueError('Dataset must not be empty')
    return d


def _require(d: pd.DataFrame, columns: list[str], key: str | None = None) -> None:
    missing = set(columns) - set(d.columns)
    if missing:
        raise ValueError(f'Missing columns: {sorted(missing)}')
    if d[columns].isna().any().any():
        raise ValueError('Null values in required columns')
    if key and not d[key].is_unique:
        raise ValueError(f'Duplicate primary key {key}')


def _nonneg(d: pd.DataFrame, columns: list[str]) -> None:
    if (~np.isfinite(d[columns].to_numpy(dtype=float))).any() or (d[columns]<0).any().any():
        raise ValueError('Non-finite or negative numeric measure')


def _safe_ratio(a: float, b: float) -> float:
    return float(a/b) if b else 0.0


def operator_training(d: pd.DataFrame):
    _require(d,['operator_id','shift','training_hours','pre_score','post_score','quality_before_pct','quality_after_pct'],key='operator_id')
    _nonneg(d,['training_hours','pre_score','post_score','quality_before_pct','quality_after_pct'])
    if (d[['pre_score','post_score','quality_before_pct','quality_after_pct']]>100).any().any(): raise ValueError('Score outside 0–100')
    d=d.copy(); d['learning_gain']=d.post_score-d.pre_score; d['quality_gain_pp']=d.quality_after_pct-d.quality_before_pct
    rng=np.random.default_rng(15001); v=d.learning_gain.to_numpy(); n=len(v)
    ci=np.quantile(rng.choice(v, size=(400,n), replace=True).mean(axis=1), [0.025,0.975]).tolist()
    per=d.groupby('shift',as_index=False).agg(operators=('operator_id','count'),mean_gain=('learning_gain','mean'),quality_gain_pp=('quality_gain_pp','mean'))
    return {'project':1,'operators':n,'training_hours_total':round(float(d.training_hours.sum()),2),'mean_pre':round(float(d.pre_score.mean()),2),'mean_post':round(float(d.post_score.mean()),2),'paired_gain_pp':round(float(v.mean()),2),'bootstrap_95pct_ci_pp':[round(float(x),2) for x in ci], 'quality_gain_pp':round(float(d.quality_gain_pp.mean()),2),'per_shift':per.round(3).to_dict('records'),'interpretation':'Paired descriptive improvement on synthetic operators. NOT causal training impact.'}, d


def aftermarket_sales(d: pd.DataFrame):
    cols=['transaction_id','date','sku','channel','units_sold','units_returned','unit_price_brl','unit_cost_brl','beginning_stock','received_units']
    _require(d,cols,'transaction_id');_nonneg(d,['units_sold','units_returned','unit_price_brl','unit_cost_brl','beginning_stock','received_units'])
    if (d.units_returned>d.units_sold).any() or (d.units_sold>d.beginning_stock+d.received_units).any(): raise ValueError('Impossible inventory or returns')
    d=d.copy();d['net_units']=d.units_sold-d.units_returned;d['net_revenue_brl']=d.net_units*d.unit_price_brl;d['gross_profit_brl']=d.net_units*(d.unit_price_brl-d.unit_cost_brl);d['ending_stock']=d.beginning_stock+d.received_units-d.units_sold+d.units_returned
    s=d.groupby('sku',as_index=False).agg(revenue=('net_revenue_brl','sum'),units=('net_units','sum'),gross_profit=('gross_profit_brl','sum'),ending_stock=('ending_stock','sum')).sort_values('revenue',ascending=False)
    total=float(s.revenue.sum());s['share_cumulative']=s.revenue.cumsum()/total if total else 0;s['abc']=np.select([s.share_cumulative<=.8,s.share_cumulative<=.95],['A','B'],default='C')
    return {'project':2,'orders':len(d),'net_revenue_brl':round(total,2),'gross_profit_brl':round(float(d.gross_profit_brl.sum()),2),'gross_margin_pct':round(100*_safe_ratio(d.gross_profit_brl.sum(),total),2),'returned_units':int(d.units_returned.sum()),'sku_abc':s.round(3).to_dict('records'),'interpretation':'Synthetic transaction and inventory analytics; no ERP/SAP connection.'}, d


def documentation_catalog(d: pd.DataFrame):
    cols=['document_id','asset_id','doc_type','revision','effective_date','owner','required_fields','completed_fields','sensor_tag','sensor_units','last_reviewed','is_active']
    _require(d,cols,'document_id');_nonneg(d,['required_fields','completed_fields','revision','is_active'])
    if (d.completed_fields>d.required_fields).any() or (~d.is_active.isin([0,1])).any() or (d.required_fields==0).any():raise ValueError('Invalid documentation metadata')
    d=d.copy();d['review_age_days']=(pd.Timestamp('2026-10-21')-pd.to_datetime(d.last_reviewed)).dt.days
    if (d.review_age_days<0).any():raise ValueError('Review in future')
    d['complete']=d.completed_fields.eq(d.required_fields);d['stale']=d.review_age_days>365
    dup=d.duplicated(subset=['asset_id','doc_type','revision'],keep=False)
    if dup.any(): raise ValueError('Duplicate asset/type/revision combination')
    d['telemetry_mapped']=d.sensor_tag.astype(str).str.len().gt(3) & d.sensor_units.astype(str).str.len().gt(0)
    active=d[d.is_active==1]
    per=d.groupby('doc_type',as_index=False).agg(count=('document_id','count'),complete_pct=('complete','mean'),stale_pct=('stale','mean'))
    return {'project':3,'documents':len(d),'active_documents':len(active),'metadata_completeness_pct':round(100*float(d.completed_fields.sum()/d.required_fields.sum()),2),'stale_documents':int(d.stale.sum()),'mapped_telemetry_pct':round(100*float(d.telemetry_mapped.mean()),2),'by_type':per.round(4).to_dict('records'),'interpretation':'Metadata quality and tag mapping on synthetic catalog; no deployed document index.'},d


def nvh_fft(d: pd.DataFrame):
    _require(d,['sample_index','sample_rate_hz','accel_g','rpm','cylinders'],'sample_index');_nonneg(d,['sample_rate_hz','rpm','cylinders'])
    if len(d)<64 or d.sample_rate_hz.nunique()!=1 or d.rpm.nunique()!=1 or d.cylinders.nunique()!=1:raise ValueError('Signal must be stationary and sufficiently sampled')
    fs=float(d.sample_rate_hz.iloc[0]);rpm=float(d.rpm.iloc[0]);cyl=int(d.cylinders.iloc[0]);fund=rpm/60*cyl/2
    if fs<=0 or fund<=0 or fs<=2*fund:raise ValueError('Aliased firing frequency (Nyquist)')
    d=d.sort_values('sample_index');idx=d.sample_index.to_numpy();
    if not np.array_equal(idx,np.arange(len(d))):raise ValueError('Missing or non-monotonic sample indices')
    signal=d.accel_g.to_numpy(dtype=float)
    if not np.isfinite(signal).all():raise ValueError('Signal contains non-finite samples')
    y=signal-signal.mean();win=np.hanning(len(signal));amp=2*np.abs(np.fft.rfft(y*win))/win.sum(); freq=np.fft.rfftfreq(len(signal),1/fs);amp[0]=0
    dominant=int(np.argmax(amp)); harmonics=[{'order':i,'expected_hz':round(i*fund,2),'amplitude_g':round(float(amp[np.argmin(abs(freq-i*fund))]),5)} for i in (1,2,3) if i*fund<fs/2]
    d=d.copy();d['time_s']=d.sample_index/fs
    return {'project':4,'samples':len(d),'sample_rate_hz':fs,'nyquist_hz':fs/2,'rms_g':round(float(np.sqrt(np.mean(y*y))),5),'firing_hz':round(fund,2),'dominant_peak_hz':round(float(freq[dominant]),2),'dominant_amplitude_g':round(float(amp[dominant]),5),'harmonics':harmonics,'interpretation':'Actual Hann-window FFT of synthetic engine vibration; not a calibrated test-bench measurement.'},d


def knowledge_base(d: pd.DataFrame):
    cols=['event_id','date','topic','operator_id','articles_viewed','feedback_score','ticket_opened','resolved_without_ticket','minutes_spent']
    _require(d,cols,'event_id');_nonneg(d,['articles_viewed','feedback_score','ticket_opened','resolved_without_ticket','minutes_spent'])
    if (d.feedback_score>5).any() or (~d.ticket_opened.isin([0,1])).any() or (~d.resolved_without_ticket.isin([0,1])).any():raise ValueError('Invalid feedback/ticket flags')
    if ((d.ticket_opened==1)&(d.resolved_without_ticket==1)).any():raise ValueError('Conflicting resolution flags')
    per=d.groupby('topic',as_index=False).agg(sessions=('event_id','count'),self_service_pct=('resolved_without_ticket','mean'),feedback_mean=('feedback_score','mean'),views=('articles_viewed','sum'))
    return {'project':5,'sessions':len(d),'active_operators':int(d.operator_id.nunique()),'article_views':int(d.articles_viewed.sum()),'self_service_session_pct':round(100*float(d.resolved_without_ticket.mean()),2),'support_ticket_sessions':int(d.ticket_opened.sum()),'by_topic':per.round(4).to_dict('records'),'interpretation':'Self-service correlation in synthetic portal data, NOT measured helpdesk ticket reduction.'},d


def procurement_funnel(d: pd.DataFrame):
    cols=['request_id','request_date','approved_date','po_date','receipt_date','department','supplier','request_value_brl','quoted_value_brl','received_value_brl','status']
    _require(d,cols,'request_id');_nonneg(d,['request_value_brl','quoted_value_brl','received_value_brl'])
    d=d.copy();dtcols=['request_date','approved_date','po_date','receipt_date'];
    for c in dtcols:d[c]=pd.to_datetime(d[c],errors='coerce')
    if d[dtcols].isna().any().any():raise ValueError('Invalid date')
    if (d.approved_date<d.request_date).any() or (d.po_date<d.approved_date).any() or (d.receipt_date<d.po_date).any():raise ValueError('Invalid process chronology')
    if (d.status!='received').any(): raise ValueError('This case requires completed receiving records')
    d['cycle_days']=(d.receipt_date-d.request_date).dt.days;d['purchase_savings_brl']=d.request_value_brl-d.quoted_value_brl;d['delivery_variance_brl']=d.received_value_brl-d.quoted_value_brl
    by=d.groupby('department',as_index=False).agg(orders=('request_id','count'),cycle_days_mean=('cycle_days','mean'),spend=('received_value_brl','sum'))
    return {'project':6,'requests_received':len(d),'average_cycle_days':round(float(d.cycle_days.mean()),2),'p90_cycle_days':round(float(d.cycle_days.quantile(.9)),2),'requested_brl':round(float(d.request_value_brl.sum()),2),'received_brl':round(float(d.received_value_brl.sum()),2),'estimated_quote_savings_brl':round(float(d.purchase_savings_brl.sum()),2),'by_department':by.round(3).to_dict('records'),'interpretation':'Synthetic completed-funnel analytics; unapproved/cancelled requests require a separate cohort.'},d


def purchasing_behavior(d: pd.DataFrame):
    cols=['po_id','date','customer','tier','supplier','part_family','quantity','unit_price_brl','unit_cost_brl']
    _require(d,cols,'po_id');_nonneg(d,['quantity','unit_price_brl','unit_cost_brl'])
    d=d.copy();d['spend_brl']=d.quantity*d.unit_price_brl;d['gross_margin_brl']=d.quantity*(d.unit_price_brl-d.unit_cost_brl)
    per=d.groupby('customer',as_index=False).agg(orders=('po_id','count'),spend=('spend_brl','sum'))
    suppliers=d.groupby('supplier').spend_brl.sum();weights=suppliers/suppliers.sum();hhi=float((weights**2).sum())
    return {'project':7,'purchase_orders':len(d),'customers':int(d.customer.nunique()),'repeat_customer_pct':round(100*float((per.orders>1).mean()),2),'total_spend_brl':round(float(d.spend_brl.sum()),2),'supplier_hhi':round(hhi,4),'top_customers':per.sort_values('spend',ascending=False).head(5).round(2).to_dict('records'),'by_tier':d.groupby('tier').spend_brl.sum().round(2).to_dict(),'interpretation':'Synthetic purchase concentration; HHI based on spend shares, not market share.'},d


def shift_utilities(d: pd.DataFrame):
    cols=['reading_id','day','shift','line','kwh','produced_units','planned_hours','run_hours','tariff_brl_kwh']
    _require(d,cols,'reading_id');_nonneg(d,['kwh','produced_units','planned_hours','run_hours','tariff_brl_kwh'])
    if (d.run_hours>d.planned_hours).any() or (d.produced_units==0).any():raise ValueError('Impossible shift metrics')
    d=d.copy();d['kwh_per_unit']=d.kwh/d.produced_units;d['electric_cost_brl']=d.kwh*d.tariff_brl_kwh
    group=d.groupby('shift',as_index=False).agg(kwh=('kwh','sum'),units=('produced_units','sum'),cost_brl=('electric_cost_brl','sum'));group['kwh_per_unit']=group.kwh/group.units
    return {'project':8,'readings':len(d),'total_kwh':round(float(d.kwh.sum()),2),'units':int(d.produced_units.sum()),'weighted_kwh_per_unit':round(float(d.kwh.sum()/d.produced_units.sum()),4),'total_cost_brl':round(float(d.electric_cost_brl.sum()),2),'by_shift':group.round(4).to_dict('records'),'interpretation':'Intensity denominator accounts for units; compare product mix before attributing causes.'},d


def asset_valuation(d: pd.DataFrame):
    cols=['asset_id','acquisition_cost_brl','age_years','useful_life_years','salvage_fraction','annual_net_cashflow_brl','discount_rate','remaining_horizon_years']
    _require(d,cols,'asset_id');_nonneg(d,cols[1:]);
    if (d.useful_life_years<=0).any() or (d.discount_rate>=1).any() or (d.salvage_fraction>1).any() or (d.remaining_horizon_years>40).any():raise ValueError('Invalid depreciation or DCF assumptions')
    d=d.copy();d['depreciable_brl']=d.acquisition_cost_brl*(1-d.salvage_fraction)
    d['book_value_brl']=np.maximum(d.acquisition_cost_brl-d.depreciable_brl*np.minimum(d.age_years/d.useful_life_years,1),d.acquisition_cost_brl*d.salvage_fraction)
    years=d.remaining_horizon_years.to_numpy().astype(int);discount=d.discount_rate.to_numpy();annual=d.annual_net_cashflow_brl.to_numpy();salvage=d.acquisition_cost_brl.to_numpy()*d.salvage_fraction.to_numpy()
    npv=[]
    for horizon,r,c,sal in zip(years,discount,annual,salvage):npv.append(float(sum(c/(1+r)**i for i in range(1,horizon+1))+sal/(1+r)**horizon))
    d['illustrative_cashflow_pv_brl']=npv
    return {'project':9,'assets':len(d),'gross_book_cost_brl':round(float(d.acquisition_cost_brl.sum()),2),'depreciated_book_value_brl':round(float(d.book_value_brl.sum()),2),'illustrative_future_cashflow_pv_brl':round(float(d.illustrative_cashflow_pv_brl.sum()),2),'by_asset':d[['asset_id','book_value_brl','illustrative_cashflow_pv_brl']].round(2).to_dict('records'),'interpretation':'Discounted illustrative net cashflows exclude purchase price as sunk cost; NOT external market valuation.'},d

FUNCS={1:operator_training,2:aftermarket_sales,3:documentation_catalog,4:nvh_fft,5:knowledge_base,6:procurement_funnel,7:purchasing_behavior,8:shift_utilities,9:asset_valuation}


def run(project: int, source: str | Path | None = None) -> dict:
    if not isinstance(project,int) or project not in FUNCS:raise ValueError('Unsupported project (001–009)')
    d=_read(project,source)
    result,_=FUNCS[project](d)
    return {'dataset':'synthetic / reproducible, not operational evidence',**result}


def save_report(project:int, destination: str | Path) -> dict:
    """Save a report, an underlying QA-verified dataset view, and one SVG plot."""
    from matplotlib import pyplot as plt
    out=Path(destination);out.mkdir(parents=True,exist_ok=True)
    d=_read(project);result,view=FUNCS[project](d)
    result={'dataset':'synthetic / reproducible, not operational evidence',**result}
    (out/'metrics.json').write_text(json.dumps(result,ensure_ascii=False,indent=2),encoding='utf-8')
    view.to_csv(out/'validated_data.csv',index=False)
    fig,ax=plt.subplots(figsize=(8,3.5))
    if project==1: ax.bar(['Pre','Post'],[view.pre_score.mean(),view.post_score.mean()]);ax.set_ylabel('Mean test score (0-100)')
    elif project==2: view.groupby('sku').net_revenue_brl.sum().sort_values().plot.barh(ax=ax);ax.set_xlabel('Net revenue BRL')
    elif project==3: view.groupby('doc_type').complete.mean().sort_values().plot.barh(ax=ax);ax.set_xlabel('Complete share')
    elif project==4: ax.plot(view.time_s.iloc[:400],view.accel_g.iloc[:400]);ax.set_xlabel('Time s');ax.set_ylabel('Acceleration g')
    elif project==5: view.groupby('topic').resolved_without_ticket.mean().sort_values().plot.barh(ax=ax);ax.set_xlabel('Self service share')
    elif project==6: view.groupby('department').cycle_days.mean().sort_values().plot.barh(ax=ax);ax.set_xlabel('Mean request-to-receipt days')
    elif project==7: view.groupby('supplier').spend_brl.sum().sort_values().plot.barh(ax=ax);ax.set_xlabel('Spend BRL')
    elif project==8: (view.groupby('shift').kwh.sum()/view.groupby('shift').produced_units.sum()).plot.bar(ax=ax);ax.set_ylabel('kWh per unit')
    elif project==9: view.set_index('asset_id')[['book_value_brl','illustrative_cashflow_pv_brl']].plot.bar(ax=ax);ax.set_ylabel('BRL')
    ax.set_title(f'Project #{project:03d} — SYNTHETIC DEMO')
    fig.tight_layout();fig.savefig(out/'chart.svg');plt.close(fig)
    return result

