// Shared helpers for the phase-3 science sections (#014, #102, #111): tables, forest plots,
// banded line charts and reliability diagrams, all plain SVG built on the lap-simulator helpers.
import { el, text, clear, fmt, richHTML, scale, niceTicks, axes, path } from '../lapsim/charts.js';

export const INK = '#1c2128', SLATE = '#59616b', RULE = '#e3e6ea';
export const BLUE = '#1d4e9e', RED = '#b8122b', GREEN = '#1b7a48', AMBER = '#a85d00', GREY = '#8a929c';
export const $ = id => document.getElementById(id);
export const sgn = (x, d = 2) => (x >= 0 ? '+' : '−') + fmt(Math.abs(x), d);
export const pct = (x, d = 0) => fmt(100 * x, d) + ' %';

export async function getJSON(url) {
  const r = await fetch(url);
  if (!r.ok) throw new Error(`${url}: HTTP ${r.status}`);
  return r.json();
}

export function table(id, head, rows) {
  const t = $(id);
  t.querySelectorAll('thead,tbody').forEach(e => e.remove());
  const th = t.createTHead().insertRow();
  head.forEach(h => { const c = document.createElement('th'); c.scope = 'col'; c.innerHTML = richHTML(h); th.append(c); });
  const tb = t.createTBody();
  rows.forEach(r => {
    const tr = tb.insertRow();
    r.forEach((v, i) => {
      const c = i ? tr.insertCell() : document.createElement('th');
      if (!i) { c.scope = 'row'; tr.append(c); }
      // values are generated by our own builders; <small>/<strong> carry intervals and choices
      c.innerHTML = /<(small|strong)>/.test(v) ? v : richHTML(v);
    });
  });
}

function niceStep(raw) { const m = 10 ** Math.floor(Math.log10(raw || 1)); return [1, 2, 5, 10].map(k => k * m).find(s => s >= raw) || raw; }

// rows [{label, mean, lo, hi, color, note}]
export function forest(svg, rows, { width = 760, rowH = 18, xLabel, zero = true, d = 2, left = 120 } = {}) {
  clear(svg);
  const h = 30 + rows.length * rowH + 40;
  svg.setAttribute('viewBox', `0 0 ${width} ${h}`);
  const box = { l: left, r: width - 150, t: 20, b: 20 + rows.length * rowH };
  const lo = Math.min(...rows.map(r => r.lo), zero ? 0 : Infinity), hi = Math.max(...rows.map(r => r.hi), zero ? 0 : -Infinity);
  const pad = (hi - lo) * 0.06 || 1;
  const x = v => box.l + (v - (lo - pad)) / ((hi + pad) - (lo - pad)) * (box.r - box.l);
  const g = el('g', { 'font-size': 11, fill: SLATE }, svg);
  const step = niceStep((hi - lo) / 6);
  for (let v = Math.ceil((lo - pad) / step) * step; v <= hi + pad; v += step) {
    el('line', { x1: x(v), x2: x(v), y1: box.t - 6, y2: box.b, stroke: RULE }, g);
    text(g, x(v), box.b + 16, fmt(Math.abs(v) < 1e-9 ? 0 : v, d), { 'text-anchor': 'middle' });
  }
  if (zero) el('line', { x1: x(0), x2: x(0), y1: box.t - 6, y2: box.b, stroke: INK }, g);
  if (xLabel) text(g, (box.l + box.r) / 2, box.b + 32, xLabel, { 'text-anchor': 'middle', fill: INK });
  rows.forEach((r, i) => {
    const y = box.t + i * rowH + rowH / 2;
    text(svg, box.l - 8, y + 4, r.label, { 'text-anchor': 'end', 'font-size': 11, fill: INK });
    el('line', { x1: x(r.lo), x2: x(r.hi), y1: y, y2: y, stroke: r.color || INK, 'stroke-width': 2 }, svg);
    el('circle', { cx: x(r.mean), cy: y, r: 3.6, fill: r.color || INK }, svg);
    if (r.note) text(svg, box.r + 8, y + 4, r.note, { 'font-size': 10.5, fill: SLATE });
  });
}

// Line chart with optional shaded bands: series [{x:[], y:[], color, dash, width, label, band:{lo:[],hi:[]}}],
// hbands [{lo, hi, color, label}] for horizontal reference bands, hlines [{y, color, dash, label}].
export function chart(svg, series, { width = 760, height = 300, xLabel, yLabel, xDomain, yDomain, xFmt, yFmt, hbands = [], hlines = [], vlines = [], legend = true }) {
  clear(svg);
  svg.setAttribute('viewBox', `0 0 ${width} ${height}`);
  const box = { l: 52, r: width - 14, t: 40, b: height - 40 };
  const all = series.flatMap(s => s.x);
  const xd = xDomain || [Math.min(...all), Math.max(...all)];
  const ys = series.flatMap(s => [...s.y, ...(s.band ? [...s.band.lo, ...s.band.hi] : [])]).filter(v => v !== null && Number.isFinite(v));
  const yd = yDomain || [Math.min(...ys), Math.max(...ys)];
  const x = scale(xd[0], xd[1], box.l, box.r), y = scale(yd[0], yd[1], box.b, box.t);
  axes(svg, { x, y, xTicks: niceTicks(...xd, 6), yTicks: niceTicks(...yd, 5), box, xLabel, yLabel, xFmt, yFmt });
  const clip = v => Math.max(yd[0], Math.min(yd[1], v));
  hbands.forEach(b => el('rect', { x: box.l, width: box.r - box.l, y: y(clip(b.hi)), height: Math.max(y(clip(b.lo)) - y(clip(b.hi)), 0), fill: b.color, opacity: 0.35 }, svg));
  hlines.forEach(h => el('line', { x1: box.l, x2: box.r, y1: y(h.y), y2: y(h.y), stroke: h.color || SLATE, 'stroke-dasharray': h.dash || '4 3', 'stroke-width': 1.2 }, svg));
  vlines.forEach(v => {
    if (v.x < xd[0] || v.x > xd[1]) return;
    el('line', { x1: x(v.x), x2: x(v.x), y1: box.t, y2: box.b, stroke: v.color || SLATE, 'stroke-dasharray': v.dash || '3 3', 'stroke-width': 1 }, svg);
    if (v.label) text(svg, x(v.x) + 3, box.t + 10 + (v.dy || 0), v.label, { 'font-size': 10, fill: v.color || SLATE });
  });
  series.forEach(s => {
    if (!s.band) return;
    const up = [], dn = [];
    s.x.forEach((xv, i) => { if (xv >= xd[0] && xv <= xd[1] && s.band.lo[i] !== null && s.band.hi[i] !== null) { up.push([xv, clip(s.band.hi[i])]); dn.push([xv, clip(s.band.lo[i])]); } });
    const d = path(up, x, y) + ' L' + dn.reverse().map(p => `${x(p[0]).toFixed(1)},${y(p[1]).toFixed(1)}`).join(' L') + ' Z';
    el('path', { d, fill: s.color, opacity: 0.16, stroke: 'none' }, svg);
  });
  series.forEach(s => {
    const pts = s.x.map((xv, i) => [xv, s.y[i]]).filter(p => p[0] >= xd[0] && p[0] <= xd[1] && p[1] !== null && Number.isFinite(p[1])).map(p => [p[0], clip(p[1])]);
    if (s.dots) {
      pts.forEach(p => el('circle', { cx: x(p[0]), cy: y(p[1]), r: s.r || 1.8, fill: s.color, opacity: s.opacity ?? 0.6 }, svg));
      return;
    }
    el('path', { d: path(pts, x, y), fill: 'none', stroke: s.color, 'stroke-width': s.width || 1.6, 'stroke-dasharray': s.dash, 'stroke-linejoin': 'round' }, svg);
  });
  if (!legend) return { x, y, box };
  const lg = el('g', { 'font-size': 11 }, svg);
  let lx = box.l;
  [...series.filter(s => s.label), ...hbands.filter(b => b.label).map(b => ({ ...b, swatch: true }))].forEach(s => {
    if (s.swatch) el('rect', { x: lx, y: 5, width: 16, height: 10, fill: s.color, opacity: 0.5 }, lg);
    else if (s.dots) el('circle', { cx: lx + 8, cy: 10, r: 3.5, fill: s.color }, lg);
    else el('line', { x1: lx, x2: lx + 16, y1: 10, y2: 10, stroke: s.color, 'stroke-width': 2.4, 'stroke-dasharray': s.dash }, lg);
    text(lg, lx + 20, 14, s.label, { fill: INK });
    lx += 30 + s.label.length * 6.1;
  });
  return { x, y, box };
}

// Reliability diagram: models [{bins:[{forecast, observed, lo, hi, n}], color, label, ci}]
export function reliability(svg, models, { size = 260, title } = {}) {
  clear(svg);
  svg.setAttribute('viewBox', `0 0 ${size} ${size + 20}`);
  const box = { l: 40, r: size - 10, t: 26, b: size - 22 };
  const x = scale(0, 1, box.l, box.r), y = scale(0, 1, box.b, box.t);
  axes(svg, { x, y, xTicks: [0, 0.25, 0.5, 0.75, 1], yTicks: [0, 0.25, 0.5, 0.75, 1], box, xLabel: 'probabilidade prevista', yLabel: '',
    xFmt: v => fmt(v, 2), yFmt: v => fmt(v, 2) });
  el('line', { x1: x(0), y1: y(0), x2: x(1), y2: y(1), stroke: GREY, 'stroke-dasharray': '4 3' }, svg);
  if (title) text(svg, box.l, 14, title, { 'font-size': 12, 'font-weight': 600, fill: INK });
  models.forEach(m => {
    m.bins.forEach(b => {
      if (m.ci) el('line', { x1: x(b.forecast), x2: x(b.forecast), y1: y(b.lo), y2: y(b.hi), stroke: m.color, 'stroke-width': 1.2, opacity: 0.6 }, svg);
      el('circle', { cx: x(b.forecast), cy: y(b.observed), r: Math.min(2 + Math.sqrt(b.n) / 3, 8), fill: m.fill === false ? '#fff' : m.color, stroke: m.color, 'stroke-width': 1.4, opacity: 0.9 }, svg);
    });
  });
}

// Grouped horizontal bars of proportions: groups [{label, bars:[{name, v, color}]}]
export function bars(svg, groups) {
  clear(svg);
  const W = 760, rh = 22, H = 30 + groups.reduce((a, g) => a + 22 + g.bars.length * rh + 14, 0) + 30;
  svg.setAttribute('viewBox', `0 0 ${W} ${H}`);
  const l = 230, r = W - 60, x = v => l + v * (r - l);
  for (let v = 0; v <= 1.0001; v += 0.25) {
    el('line', { x1: x(v), x2: x(v), y1: 20, y2: H - 30, stroke: RULE }, svg);
    text(svg, x(v), H - 12, pct(v, 0), { 'text-anchor': 'middle', 'font-size': 10.5, fill: SLATE });
  }
  let y = 26;
  groups.forEach(g => {
    text(svg, 10, y + 12, g.label, { 'font-size': 11.5, 'font-weight': 600, fill: INK });
    y += 22;
    g.bars.forEach(b => {
      el('rect', { x: l, y, width: Math.max(x(b.v) - l, 1), height: rh - 6, fill: b.color }, svg);
      text(svg, l - 8, y + 12, b.name, { 'text-anchor': 'end', 'font-size': 11, fill: SLATE });
      text(svg, x(b.v) + 6, y + 12, pct(b.v, 1), { 'font-size': 11, fill: INK });
      y += rh;
    });
    y += 14;
  });
}

